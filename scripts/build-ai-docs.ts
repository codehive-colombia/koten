export function renderInventory(siteUrl: string): string {
  const components = allPrimitiveDocs.map(
    (doc) => `| ${doc.name} | ${doc.id} | \`${registryName(doc)}\` | ${pageUrl(doc, siteUrl)} |`,
  );
  const blocks = allBlockDocs.map(
    (doc) =>
      `| ${doc.name} | ${doc.id} | ${doc.category} | \`${registryName(doc)}\` | ${pageUrl(doc, siteUrl)} |`,
  );

  return [
    "# Koten UI inventory",
    "",
    "Generated from `apps/catalog/src/data/docs` by `bun run ai:docs`. Do not edit by hand.",
    "",
    `Use the registry item with \`npx shadcn@latest add ${siteUrl}/r/<item>.json\`. Install \`koten-theme\` first when the project has no Koten tokens.`,
    "",
    `## Components (${allPrimitiveDocs.length})`,
    "",
    "| Component | ID | Registry item | Catalog page |",
    "| --- | --- | --- | --- |",
    ...components,
    "",
    `## Blocks (${allBlockDocs.length})`,
    "",
    "| Block | ID | Category | Registry item | Catalog page |",
    "| --- | --- | --- | --- | --- |",
    ...blocks,
    "",
    "## Rules of thumb",
    "",
    "- Prefer an existing primitive or block over a new component.",
    "- A primitive is a single, reusable piece with a public API. A block composes primitives for a concrete screen.",
    "- Do not rewrite the installed source to change the theme: change `data-theme`/`data-density` or the token roles.",
    "- Form controls pair with `Field` or `FormRow`; overlays need a portal and focus return; `Toast` needs `ToastProvider`.",
    "",
  ].join("\n");
}

function guide(root: string, file: string, title: string, description: string): BuiltDoc {
  const source = readFileSync(join(root, "docs", file), "utf8");

  return {
    path: `md/guides/${file.replace(/\.md$/, "").toLowerCase()}.md`,
    content: [
      "---",
      `title: ${yaml(title)}`,
      `description: ${yaml(description)}`,
      "language: es",
      "---",
      "",
      source,
    ].join("\n"),
  };
}

/** Files served from the catalog public directory. */
export function buildSiteDocs({ siteUrl, root }: BuildOptions): BuiltDoc[] {
  const docs: BuiltDoc[] = [
    { path: "llms.txt", content: renderLlmsTxt(siteUrl) },
    ...allPrimitiveDocs.map((doc) => ({
      path: `md/components/${doc.slug}.md`,
      content: renderDoc(doc, siteUrl),
    })),
    ...allBlockDocs.map((doc) => ({
      path: `md/blocks/${doc.category}/${doc.slug}.md`,
      content: renderDoc(doc, siteUrl),
    })),
    guide(
      root,
      "DESIGN-SYSTEM.md",
      "Koten UI design system",
      "Visual grammar, tokens, component language, i18n, accessibility and performance rules.",
    ),
    guide(
      root,
      "RECIPES.md",
      "Koten UI recipes",
      "Copy-ready form, table, drawer, product card and i18n recipes.",
    ),
  ];

  const pageDocs = docs.filter((doc) => doc.path.startsWith("md/"));

  return [
    ...docs,
    {
      path: "llms-full.txt",
      content: [
        "# Koten UI — full documentation",
        "",
        "> Generated from the catalog and internal guides. Prefer the per-page Markdown when you need one component; use this file to load the whole system.",
        "",
        ...pageDocs.map((doc) => `---\n\n${doc.content.trim()}\n`),
        "",
      ].join("\n"),
    },
  ];
}

/** Files committed to the repository and kept in sync by `--check`. */
export function buildTrackedDocs({ siteUrl }: BuildOptions): BuiltDoc[] {
  return [
    { path: "llms.txt", content: renderLlmsTxt(siteUrl) },
    {
      path: "skills/koten-ui/references/inventory.md",
      content: renderInventory(siteUrl),
    },
    {
      path: "skills/koten-ui/references/guides.md",
      content: [
        "# Koten UI guides",
        "",
        "Generated by `bun run ai:docs`. Do not edit by hand.",
        "",
        `- [Design system](${siteUrl}/md/guides/design-system.md): the grammar, tokens, component language and checklists.`,
        `- [Recipes](${siteUrl}/md/guides/recipes.md): form, table, drawer, product card, i18n and quality recipes.`,
        `- [Full documentation](${siteUrl}/llms-full.txt): every page in one file.`,
        `- [Repository docs](${repositoryUrl}/tree/main/docs): requirements, decisions, roadmap and progress.`,
        "",
      ].join("\n"),
    },
  ];
}

function writeDocs(target: string, docs: readonly BuiltDoc[]): void {
  for (const doc of docs) {
    const path = join(target, doc.path);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, doc.content, "utf8");
  }
}

export function writeSiteDocs(root: string, siteUrl: string): string[] {
  const docs = buildSiteDocs({ siteUrl, root });
  writeDocs(join(root, "apps/catalog/public"), docs);

  return docs.map((doc) => `apps/catalog/public/${doc.path}`);
}

export function writeTrackedDocs(root: string, siteUrl: string): string[] {
  const docs = buildTrackedDocs({ siteUrl, root });
  writeDocs(root, docs);

  return docs.map((doc) => doc.path);
}

function readIfExists(path: string): string | null {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

export function checkTrackedDocs(root: string, siteUrl: string): string[] {
  return buildTrackedDocs({ siteUrl, root })
    .filter((doc) => readIfExists(join(root, doc.path)) !== doc.content)
    .map((doc) => `${doc.path} is out of date`);
}

type SkillFrontmatter = {
  name?: string;
  description?: string;
};

function parseFrontmatter(source: string): SkillFrontmatter {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(source);

  if (!match) {
    return {};
  }

  const frontmatter = match[1] ?? "";
  const read = (key: string): string | undefined => {
    const line = new RegExp(`^${key}:\\s*(.+)$`, "m").exec(frontmatter)?.[1]?.trim();

    if (!line) return undefined;
    if (line.startsWith('"') && line.endsWith('"')) {
      try {
        return JSON.parse(line) as string;
      } catch {
        return line.slice(1, -1);
      }
    }

    return line;
  };

  return { name: read("name"), description: read("description") };
}

/** Validates the Agent Skills frontmatter and every relative reference. */
export function validateSkills(root: string): string[] {
  const skillsRoot = join(root, "skills");
  const failures: string[] = [];

  if (!existsSync(skillsRoot)) {
    return ["skills/ does not exist"];
  }

  const directories = readdirSync(skillsRoot).filter((entry) => {
    const path = join(skillsRoot, entry);

    return statSync(path).isDirectory() && existsSync(join(path, "SKILL.md"));
  });

  if (directories.length === 0) {
    failures.push("skills/ has no <name>/SKILL.md directories");
  }

  for (const directory of directories) {
    const path = join(skillsRoot, directory, "SKILL.md");
    const source = readFileSync(path, "utf8");
    const { name, description } = parseFrontmatter(source);

    if (!source.startsWith("---")) {
      failures.push(`${directory}: SKILL.md must start with YAML frontmatter`);
    }
    if (!name) {
      failures.push(`${directory}: missing name`);
    } else {
      if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) {
        failures.push(`${directory}: invalid name "${name}"`);
      }
      if (name !== directory) {
        failures.push(`${directory}: name must match the directory`);
      }
    }
    if (!description) {
      failures.push(`${directory}: missing description`);
    } else if (description.length > 1024) {
      failures.push(`${directory}: description is longer than 1024 characters`);
    }

    const body = source.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, "");

    if (body.trim().length < 80) {
      failures.push(`${directory}: SKILL.md body is too short`);
    }
    if (body.length > 20_000) {
      failures.push(
        `${directory}: SKILL.md is longer than 20 000 characters; move detail to references/`,
      );
    }

    for (const match of body.matchAll(/(?:references|scripts|assets)\/[A-Za-z0-9_./-]+/g)) {
      const reference = match[0];

      if (!existsSync(join(skillsRoot, directory, reference))) {
        failures.push(`${directory}: missing referenced file ${reference}`);
      }
    }
  }

  return failures;
}

function main(): void {
  const root = findRoot();
  const siteUrl = normalizeSiteUrl(process.env.KOTEN_SITE_URL);
  // Tracked files always point at production so a local `predev` does not dirty
  // the repository with localhost URLs.
  const trackedSiteUrl = normalizeSiteUrl(undefined);

  if (process.argv.includes("--check")) {
    const failures = [...checkTrackedDocs(root, trackedSiteUrl), ...validateSkills(root)];

    if (failures.length > 0) {
      console.error("AI documentation check failed:\n");
      for (const failure of failures) console.error(`- ${failure}`);
      console.error("\nRun `bun run ai:docs` to regenerate the tracked files.");
      process.exit(1);
    }

    console.log("AI documentation and skills are in sync.");
    return;
  }

  const siteFiles = writeSiteDocs(root, siteUrl);
  const trackedFiles = writeTrackedDocs(root, trackedSiteUrl);

  console.log(
    `AI docs: ${allPrimitiveDocs.length} components, ${allBlockDocs.length} blocks, ${siteFiles.length} site files, ${trackedFiles.length} tracked files.`,
  );
  console.log(`Site URL: ${siteUrl}`);
}

const isMain = process.argv[1]
  ? resolve(process.argv[1]) === fileURLToPath(import.meta.url)
  : false;

if (isMain) {
  main();
}

