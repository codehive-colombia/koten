/**
 * Koten UI agent documentation build.
 *
 * Generates the machine-readable layer from the same catalog data that powers
 * the website, so the docs cannot drift from the components:
 *
 * - `apps/catalog/public/llms.txt` and `llms-full.txt` (llmstxt.org format).
 * - One Markdown file per primitive (`/md/components/<slug>.md`) and block
 *   (`/md/blocks/<category>/<slug>.md`).
 * - Copies of the design system and recipes under `/md/guides/`.
 * - The tracked inventory used by the `koten-ui` skill, plus the repository
 *   `llms.txt`.
 *
 * Usage:
 *   `bun scripts/build-ai-docs.ts`          write site + tracked files
 *   `bun scripts/build-ai-docs.ts --check`  fail when tracked files are stale
 *
 * The site files are ignored by git and regenerated by the catalog `predev`
 * and `prebuild` scripts, exactly like the shadcn registry.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { allBlockDocs, allPrimitiveDocs } from "../apps/catalog/src/data/docs/all";
import type { BlockDoc, PrimitiveDoc } from "../apps/catalog/src/data/docs/types";

export const repositoryUrl = "https://github.com/codehive-colombia/koten";

type BuiltDoc = { path: string; content: string };

type BuildOptions = {
  siteUrl: string;
  /** Only needed for the guides and the repository-relative links. */
  root: string;
};

const here = dirname(fileURLToPath(import.meta.url));
const defaultRoot = resolve(here, "..");

/** Repo root: walks up until it finds the UI package. */
export function findRoot(start = defaultRoot): string {
  let directory = start;

  for (let attempt = 0; attempt < 6; attempt += 1) {
    if (existsSync(join(directory, "packages/ui/src/components/ui"))) {
      return directory;
    }

    directory = resolve(directory, "..");
  }

  return start;
}

export function normalizeSiteUrl(value: string | undefined): string {
  const fallback = "https://koten.codehive.com.co";
  const trimmed = value?.trim().replace(/\/+$/, "");

  return trimmed ? trimmed : fallback;
}

/** Registry item used by the install command; FormRow and Calendar share files. */
function registryName(doc: PrimitiveDoc | BlockDoc): string {
  return doc.registrySlug ?? doc.slug;
}

function docsPath(doc: PrimitiveDoc | BlockDoc): string {
  return "category" in doc
    ? `blocks/${doc.category}/${doc.slug}`
    : `components/${(doc as PrimitiveDoc).slug}`;
}

function pageUrl(doc: PrimitiveDoc | BlockDoc, siteUrl: string): string {
  return "category" in doc
    ? `${siteUrl}/blocks/${doc.category}/${doc.slug}`
    : `${siteUrl}/components/${(doc as PrimitiveDoc).slug}`;
}

function markdownUrl(doc: PrimitiveDoc | BlockDoc, siteUrl: string): string {
  return `${siteUrl}/md/${docsPath(doc)}.md`;
}

function installCommand(doc: PrimitiveDoc | BlockDoc, siteUrl: string): string {
  return `npx shadcn@latest add ${siteUrl}/r/${registryName(doc)}.json`;
}

/** Single-line YAML scalar that also survives quotes and backslashes. */
function yaml(value: string): string {
  return JSON.stringify(value);
}

/** Markdown table cell: pipes and newlines would break the table. */
function cell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}

function codeFence(code: string, language = "tsx"): string {
  const fence = code.includes("```") ? "````" : "```";

  return `${fence}${language}\n${code.trim()}\n${fence}`;
}

function requirementsLines(doc: PrimitiveDoc | BlockDoc): string[] {
  if (!doc.requirements || doc.requirements.length === 0) {
    return [];
  }

  return [
    "## Requirements",
    "",
    ...doc.requirements.map((item) => `- **${item.kind}** — ${item.label.en}: ${item.detail.en}`),
    "",
  ];
}

function examplesLines(doc: PrimitiveDoc | BlockDoc): string[] {
  const lines: string[] = ["## Examples", ""];

  for (const example of doc.examples) {
    lines.push(`### ${example.title.en}`, "");

    if (example.description?.en) {
      lines.push(example.description.en, "");
    }

    lines.push(codeFence(example.code), "");
  }

  if ("formExample" in doc && doc.formExample) {
    lines.push("### Use inside a form", "", doc.formExample.description.en, "");
    lines.push(codeFence(doc.formExample.code), "");
  }

  return lines;
}

function propsLines(doc: PrimitiveDoc | BlockDoc): string[] {
  return [
    "## Props",
    "",
    "| Prop | Type | Default | Notes |",
    "| --- | --- | --- | --- |",
    ...doc.props.map(
      (row) =>
        `| \`${cell(row.prop)}\` | \`${cell(row.type)}\` | \`${cell(row.default)}\` | ${cell(row.note.en)} |`,
    ),
    "",
  ];
}

function frontmatter(doc: PrimitiveDoc | BlockDoc, siteUrl: string): string[] {
  const kind = "category" in doc ? "block" : "component";
  const fields = [
    `title: ${yaml(doc.name)}`,
    `description: ${yaml(doc.description.en)}`,
    `kind: ${kind}`,
    `id: ${doc.id}`,
    `registry: ${yaml(registryName(doc))}`,
    `docs: ${yaml(pageUrl(doc, siteUrl))}`,
    `markdown: ${yaml(markdownUrl(doc, siteUrl))}`,
    `install: ${yaml(installCommand(doc, siteUrl))}`,
    "language: en",
  ];

  if ("category" in doc) {
    fields.splice(4, 0, `category: ${doc.category}`);
  }

  return ["---", ...fields, "---", ""];
}

export function renderDoc(doc: PrimitiveDoc | BlockDoc, siteUrl: string): string {
  const kind = "category" in doc ? "Block" : "Component";
  const nodeInstall = installCommand(doc, siteUrl);
  const bunInstall = nodeInstall.replace(/^npx /, "bunx ");
  const lines = [
    ...frontmatter(doc, siteUrl),
    `# ${doc.name} · ${doc.jp}`,
    "",
    `> ${kind} ${doc.id} in the Koten UI catalog.`,
    "",
    doc.description.en,
    "",
    "## Install",
    "",
    "Install `koten-theme` first when the project does not have Koten tokens yet. Use the runner of your project.",
    "",
    codeFence(`# Node\n${nodeInstall}\n\n# Bun\n${bunInstall}`, "bash"),
    "",
    "## Files",
    "",
    ...doc.files.map((file) => `- \`${file}\``),
    "",
    ...requirementsLines(doc),
  ];

  if (doc.baseUi) {
    lines.push("## Reference", "", `- Upstream primitive: ${doc.baseUi}`, "");
  }

  if ("category" in doc && doc.baseUi === undefined) {
    lines.push(
      "## Composition",
      "",
      "This block composes Koten primitives. Read the source files above before changing its anatomy.",
      "",
    );
  }

  lines.push(...examplesLines(doc), ...propsLines(doc), "## Accessibility", "");

  for (const item of doc.a11y.en) {
    lines.push(`- ${item}`);
  }

  lines.push(
    "",
    "## Sources",
    "",
    `- Catalog page: ${pageUrl(doc, siteUrl)}`,
    `- Markdown: ${markdownUrl(doc, siteUrl)}`,
    `- Repository: ${repositoryUrl}`,
    "",
  );

  return lines.join("\n");
}

function listNodes(docs: readonly (PrimitiveDoc | BlockDoc)[], siteUrl: string): string[] {
  return docs.flatMap((doc) => {
    const description = cell(doc.description.en);
    const link = `${siteUrl}/md/${docsPath(doc)}.md`;

    return [`- [${doc.name}](${link}): ${description}`];
  });
}

